        <div class="sec-head">
            <p class="label">FAQ</p>
            <h2>Good to know</h2>
        </div>
        <div class="faq">
            <details>
                <summary>Do I need to be a runner?</summary>
                <p>No. Walking is allowed. Run your own race at your own pace, and a leader will stay at the back with you.</p>
            </details>
            <details>
                <summary>Is there a running group near me in Ibadan?</summary>
                <p>LRI has tribes across the city in Akobo, Bodija, UI / Eleyele and Oluyole / Akala. Join the one closest to you, and on the first Saturday of the month every tribe runs together.</p>
            </details>
            <details>
                <summary>Does it cost anything?</summary>
                <p>Tribe runs and community runs are free. Some hangouts ask for an optional chip-in toward fruit and water, and extras like padel are paid separately.</p>
            </details>
            <details>
                <summary>Can I run with a different tribe?</summary>
                <p>Yes. Pick one home tribe for the group chats, then run with any tribe whenever you like. On the first Saturday of the month everyone runs together anyway.</p>
            </details>
            <details>
                <summary>Who leads the runs?</summary>
                <p>Our Pace Setters. They are the tribe leaders who plan routes, set the pace, keep the group together and look after new runners. LRI’s founders lead the wider community.</p>
            </details>
            <details>
                <summary>What should I bring?</summary>
                <p>Water, comfortable shoes and your phone if you track your runs on Strava. On cause days, check the group for the dress code.</p>
            </details>
        </div>
    </div>
</section>
